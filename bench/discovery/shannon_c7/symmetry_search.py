#!/usr/bin/env python3
"""Exact maximum independent sets of C7^m restricted to sets invariant under a random symmetry subgroup H.
Automorphisms used: v -> P(s * v) + t (mod 7), P coordinate permutation, s in {+-1}^m, t translation.
For each H (generated by 1-2 random automorphisms, |H| capped): orbits on V; keep orbits with no internal
conflict; maximum-weight independent set of the orbit conflict graph by MILP; verify; keep the best.
Usage: symmetry_search.py m seconds seed [max_order]
"""
import itertools
import sys
import time
import numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds
import scipy.sparse as sp

m, secs, seed = int(sys.argv[1]), float(sys.argv[2]), int(sys.argv[3])
max_order = int(sys.argv[4]) if len(sys.argv) > 4 else 400
rng = np.random.default_rng(seed)
V = np.array(list(itertools.product(range(7), repeat=m)))
n = len(V)
w7 = 7 ** np.arange(m)[::-1]
code = lambda X: (X % 7) @ w7  # noqa: E731
close = lambda a, b: (np.minimum((a - b) % 7, (b - a) % 7) <= 1).all(axis=-1)  # noqa: E731


def random_aut():
    P = rng.permutation(m)
    s = rng.choice([-1, 1], size=m)
    t = rng.integers(0, 7, size=m)
    return code(V[:, P] * s + t)


def closure(gens):
    ident = np.arange(n)
    group = {ident.tobytes(): ident}
    frontier = [ident]
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                c = h[g]
                key = c.tobytes()
                if key not in group:
                    group[key] = c
                    new.append(c)
                    if len(group) > max_order:
                        return None
        frontier = new
    return list(group.values())


def orbits(group):
    lab = -np.ones(n, dtype=int)
    orbs = []
    for v in range(n):
        if lab[v] < 0:
            o = np.unique(np.array([g[v] for g in group]))
            lab[o] = len(orbs)
            orbs.append(o)
    return orbs


best, t0, tried = 0, time.time(), 0
while time.time() - t0 < secs:
    gens = [random_aut() for _ in range(rng.integers(1, 3))]
    G = closure(gens)
    if G is None or len(G) < 4:
        continue
    tried += 1
    orbs = [o for o in orbits(G)]
    good = []
    for o in orbs:
        P = V[o]
        M = close(P[:, None, :], P[None, :, :])
        np.fill_diagonal(M, False)
        if not M.any():
            good.append(o)
    k = len(good)
    if k == 0:
        continue
    reps = [V[o] for o in good]
    E = []
    for i in range(k):
        for j in range(i + 1, k):
            if close(reps[i][:, None, :], reps[j][None, :, :]).any():
                E.append((i, j))
    w = np.array([len(o) for o in good], dtype=float)
    if w.sum() <= best:
        continue
    cons = []
    if E:
        r = np.repeat(np.arange(len(E)), 2)
        A = sp.csr_matrix((np.ones(2 * len(E)), (r, np.array(E).ravel())), shape=(len(E), k))
        cons = [LinearConstraint(A, -np.inf, 1)]
    res = milp(c=-w, constraints=cons, integrality=np.ones(k), bounds=Bounds(0, 1), options={"time_limit": 60})
    if res.x is None:
        continue
    val = int(round(-res.fun))
    if val > best:
        sel = np.concatenate([good[i] for i in range(k) if res.x[i] > 0.5])
        P = V[sel]
        M = close(P[:, None, :], P[None, :, :])
        np.fill_diagonal(M, False)
        assert not M.any() and len(sel) == val
        best = val
        print(f"m={m} seed={seed}: {best} (|H|={len(G)}, {k} admissible orbits) at {time.time() - t0:.0f}s, "
              f"verified", flush=True)
        np.save(f"/tmp/claude-0/-home-user/f5214594-0f71-5d98-9550-f6c6aba4b49e/scratchpad/sym_m{m}_s{seed}.npy",
                V[sel])
print(f"m={m} seed={seed}: best {best} after {tried} groups", flush=True)
