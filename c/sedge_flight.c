#define SF_LOG2E_Q30 UINT32_C(0x5c551d94)

/* log2(m / 2^62) in Q32 for m in [2^62, 2^63), rounded down up to a few
 * units: log2(m) = log2(m * R[j]) - log2(R[j]), with R[j] >= 64 / (64 + j)
 * rounded up (so m * R[j] = 1 + r, 0 <= r < 2^-6 + 2^-30) and -log2(R[j])
 * tabulated exactly for the rounded R[j]; then
 * ln(1 + r) ~ r - r^2/2 + r^3/3 - r^4/4 (alternating: error below
 * r^5 / 5 < 2^-32). */
static uint64_t sf_log2_q32(uint64_t m)
{
    uint64_t m32 = m >> 30;                   /* Q32, in [2^32, 2^33) */
    uint32_t j = (uint32_t)(m32 >> 26) & 63u; /* top 6 fraction bits */
    uint64_t q = m32 * SF_RECIP_Q31[j];       /* Q63, in [2^63, 2^64) */
    uint32_t r = (uint32_t)((q - (UINT64_C(1) << 63)) >> 31);  /* Q32, < 2^26.1 */
    uint32_t r2 = (uint32_t)(((uint64_t)r * r) >> 32);         /* < 2^20.2 */
    uint32_t r3 = (uint32_t)(((uint64_t)r2 * r) >> 32);        /* < 2^14.3 */
    uint32_t r4 = (uint32_t)(((uint64_t)r3 * r) >> 32);        /* < 2^8.4 */
    uint32_t ln = r - (r2 / 2u - (r3 / 3u - r4 / 4u));         /* each part >= 0 */
    return (((uint64_t)ln * SF_LOG2E_Q30) >> 30) + SF_LOG2_RECIP_Q32[j];
}

/* Subtracted (in 2^-32 bits) to make the result a lower bound: without it
 * the error is within [-7.7, +2.3] units over every surprise value, so the
 * result is 1.7 to 11.7 units below the exact value (test_flight.c). */
#define SF_EV_MARGIN 4

int64_t sedge_flight_log_evalue(uint32_t surprise, uint32_t bits_per_sample, uint32_t k)
{
    /* y = (1 - 2^-k) + 2^(u / 256) with u = surprise - 256 * (b + k):
     * y = A + 2^I * P[f], I = floor(u / 256), f = u mod 256. */
    uint64_t uo, a, pf, m;
    int64_t e;
    uint32_t f;
    if (bits_per_sample < 1u || bits_per_sample > 16u || k < 1u || k > 32u) {
        return 0;
    }
    /* u + 64 * 256 >= 0 since b + k <= 48. */
    uo = (uint64_t)surprise + 256u * (64u - bits_per_sample - k);
    e = (int64_t)(uo >> 8) - 64; /* I */
    f = (uint32_t)(uo & 255u);
    a = (UINT64_C(1) << 62) - (UINT64_C(1) << (62u - k)); /* 1 - 2^-k, Q62 */
    pf = (uint64_t)SF_EXP2_Q31[f] << 31;                  /* 2^(f/256), Q62 */
    if (e >= 0) {
        /* y / 2^I = P[f] + A * 2^-I, in [1, 3). */
        m = pf + (e < 63 ? a >> (uint32_t)e : 0u);
    } else {
        /* -48 <= I <= -1: y = A + P[f] * 2^I, in [1/2, 2). */
        m = a + (pf >> (uint32_t)(-e));
        e = 0;
    }
    if (m >= (UINT64_C(1) << 63)) {
        m >>= 1;
        e += 1;
    } else if (m < (UINT64_C(1) << 62)) {
        m <<= 1;
        e -= 1;
    }
    /* e <= 2^24 + 1, so e * 2^32 fits easily. */
    return e * (INT64_C(1) << 32) + (int64_t)sf_log2_q32(m) - SF_EV_MARGIN;
}

#define SF_CUSUM_CAP (INT64_C(1) << 62) /* 2^30 bits */

void sedge_flight_cusum_init(sedge_flight_cusum *c)
{
    uint32_t i;
    if (c != NULL) {
        for (i = 0; i < SEDGE_FLIGHT_CUSUM_N; i++) {
            c->s[i] = 0;
        }
    }
}

int sedge_flight_cusum_update(sedge_flight_cusum *c, uint32_t surprise,
                              uint32_t bits_per_sample, uint32_t t)
{
    static const uint8_t k[SEDGE_FLIGHT_CUSUM_N] = {1u, 4u, 8u, 12u};
    uint32_t i;
    if (c == NULL) {
        return 0;
    }
    for (i = 0; i < SEDGE_FLIGHT_CUSUM_N; i++) {
        /* S >= 0 and -1 bit <= x < 2^25 bits: no overflow. */
        int64_t v = c->s[i] + sedge_flight_log_evalue(surprise, bits_per_sample, k[i]);
        c->s[i] = v < 0 ? 0 : (v > SF_CUSUM_CAP ? SF_CUSUM_CAP : v);
    }
    if (t > (UINT32_C(1) << 28)) {
        t = UINT32_C(1) << 28;
    }
    return sedge_flight_cusum_score(c) >= (int64_t)(t + 2u) * (INT64_C(1) << 32);
}

int64_t sedge_flight_cusum_score(const sedge_flight_cusum *c)
{
    int64_t m = 0;
    uint32_t i;
    if (c != NULL) {
        for (i = 0; i < SEDGE_FLIGHT_CUSUM_N; i++) {
            m = c->s[i] > m ? c->s[i] : m;
        }
    }
    return m;
}

