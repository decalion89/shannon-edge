/* sedge_flight: the shannon-edge flight profile in portable C99.
 * Bit-exact port of src/flight.rs, the parts of src/coder.rs it uses
 * (finish_short drops at most 4 trailing zeros) and the squash/stretch of
 * src/math.rs. Arithmetic is on unsigned types, with explicit casts for
 * every narrowing; signed values appear only where they cannot overflow,
 * and Rust's arithmetic right shifts of negative numbers are rewritten with
 * offsets. Same results on 16-, 32- and 64-bit targets of either endianness.
 */
#include "sedge_flight.h"

#include <string.h>

#define SF_STATIC_ASSERT(name, cond) typedef char sfl_assert_##name[(cond) ? 1 : -1]

/* Inlining hint for the hot helpers; none at -Os. Override with
 * -DSEDGE_FLIGHT_INLINE=... */
#ifdef SEDGE_FLIGHT_INLINE
#define SF_INLINE SEDGE_FLIGHT_INLINE
#elif defined(__OPTIMIZE_SIZE__)
#define SF_INLINE
#else
#define SF_INLINE inline
#endif

#define SF_HEADER 64u
#define SF_MAGIC 0x53664c31u
#define SF_FRESH UINT32_C(0x800000) /* Counter::FRESH: p16 = 0x8000, n = 0 */
#define SF_W0 20000u                /* initial mixer weight */

struct sedge_flight {
    uint32_t magic;
    uint32_t bits;      /* bits per sample */
    uint32_t tb;        /* table_bits */
    uint32_t t0_bits;   /* min(tb, bits + 1) */
    uint32_t r_bits;    /* min(tb, 16) */
    uint32_t prev;      /* transition model: last two values */
    uint32_t prev2;
    uint32_t rprev;     /* residual model: last value, last length */
    uint32_t last_len;
    /* Decayed recent costs, 1/256 bits. Rust keeps them in u64, but each
     * sample costs at most (2 * 16 + 4) * 3072 < 2^17, so c - c/64 + cost
     * stays below 64 * 2^17 + 63 < 2^24: uint32_t gives the same values. */
    uint32_t cost_t;
    uint32_t cost_r;
    uint32_t pad;
    size_t overrun;
};

SF_STATIC_ASSERT(header_size, sizeof(struct sedge_flight) <= SF_HEADER);

