static uint64_t rng_next(uint64_t *s)
{
    *s ^= *s >> 12;
    *s ^= *s << 25;
    *s ^= *s >> 27;
    return *s * UINT64_C(0x2545f4914f6cdd1d);
}

/* The GEN2 stream: n samples of `bits` bits, then packet sizes (summing
 * to n) into sizes[]; returns the number of packets. */
static size_t gen2(uint32_t bits, uint64_t seed, uint16_t *s, size_t n,
                   size_t *sizes, size_t max_sizes)
{
    uint64_t rng = seed;
    uint32_t mask = (UINT32_C(1) << bits) - 1u, v = mask / 2u;
    size_t i, np = 0, left = n;
    for (i = 0; i < n; i++) {
        uint64_t r = rng_next(&rng);
        uint32_t sel = (uint32_t)(r & 1023u), x;
        if (sel == 0u) {
            v = (uint32_t)(r >> 16) & mask;
            x = v;
        } else if (sel < 8u) {
            x = (uint32_t)(r >> 20) & mask;
        } else {
            uint32_t step = (uint32_t)((r >> 10) & 7u); /* -3..4 as step - 3 */
            if (step < 3u) {
                v = v >= 3u - step ? v - (3u - step) : 0u;
            } else {
                v = v + (step - 3u) <= mask ? v + (step - 3u) : mask;
            }
            x = v;
        }
        s[i] = (uint16_t)x;
    }
    while (left > 0u && np < max_sizes) {
        size_t k = (size_t)((rng_next(&rng) >> 7) & 511u);
        k = k < left ? k : left;
        sizes[np++] = k;
        left -= k;
    }
    return np;
}

